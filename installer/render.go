package installer

import (
	"fmt"
	"net"
	"regexp"
	"strconv"
	"strings"
)

// ServerParams are the answers needed to install the server.
type ServerParams struct {
	AgentPort     int
	AppPort       int    // the desktop application listener, the only way to the interface
	Domain        string // an optional DNS name of the server, put into the certificate
	AdminUser     string
	Password      string // empty = generate
	ExtraHosts    []string
	PasswordGen   bool
	DSN           string
	ConfigPath    string
	DataDir       string
	Force         bool
	UpdateSource  string // carried over from an existing configuration on reinstall
	UpdateChannel string
}

var loginRe = regexp.MustCompile(`^[a-zA-Z0-9._-]{1,64}$`)
var domainRe = regexp.MustCompile(`^([a-zA-Z0-9]([a-zA-Z0-9-]{0,61}[a-zA-Z0-9])?\.)+[a-zA-Z]{2,}$`)

// ValidPort parses a port string.
func ValidPort(s string) (int, bool) {
	n, err := strconv.Atoi(strings.TrimSpace(s))
	return n, err == nil && n >= 1 && n <= 65535
}

// ValidLogin reports whether the login is acceptable.
func ValidLogin(s string) bool { return loginRe.MatchString(s) }

// ValidDomain reports whether s looks like a fully-qualified domain name.
func ValidDomain(s string) bool { return domainRe.MatchString(s) }

// SplitHostPort validates host:port for the agent's server address.
func SplitHostPort(s string) (string, int, bool) {
	h, p, err := net.SplitHostPort(strings.TrimSpace(s))
	if err != nil || h == "" {
		return "", 0, false
	}
	n, ok := ValidPort(p)
	return h, n, ok
}

// RenderServerConfig renders /etc/linager/server.yaml.
func RenderServerConfig(p *ServerParams, hosts []string) string {
	var b strings.Builder
	b.WriteString("# Linager server configuration (generated by `linager install`)\n")
	fmt.Fprintf(&b, "data_dir: %s\n", p.DataDir)
	b.WriteString("database:\n")
	fmt.Fprintf(&b, "  dsn: %q\n", p.DSN)
	b.WriteString("admin:\n")
	b.WriteString("  cookie_secure: auto\n")
	if p.UpdateSource != "" || p.UpdateChannel == "beta" {
		b.WriteString("update:\n")
		if p.UpdateSource != "" {
			fmt.Fprintf(&b, "  source: %q\n", p.UpdateSource)
		}
		if p.UpdateChannel == "beta" {
			b.WriteString("  channel: beta\n")
		}
	}
	if p.AppPort > 0 {
		b.WriteString("app:\n")
		fmt.Fprintf(&b, "  listen: \"0.0.0.0:%d\"\n", p.AppPort)
	}
	b.WriteString("agents:\n")
	fmt.Fprintf(&b, "  listen: \"0.0.0.0:%d\"\n", p.AgentPort)
	b.WriteString("  hosts:\n")
	for _, h := range hosts {
		fmt.Fprintf(&b, "    - %q\n", h)
	}
	return b.String()
}

